// ---------------------------------------------------------------- shared pieces

export function Reasons({ r }: { r: DeliveryRequest }) {
  if (!r.reasons || !r.reasons.length) return null;
  return <ul className="reasons">{r.reasons.map((x, i) => <li key={i} className={x.code && x.code[0] === 'F' ? 'flag' : ''}><b>{x.title}</b>{x.remedy}</li>)}</ul>;
}

function QrSvg({ code }: { code: string }) {
  // Generated by our own encoder from the pass code; contains only SVG rectangles.
  const svg = useMemo(() => { try { return qrToSvg(qrEncode(code), 3); } catch { return ''; } }, [code]);
  return <div className="qr" role="img" aria-label={'QR code for ' + code} dangerouslySetInnerHTML={{ __html: svg }} />;
}

export function Ticket({ r, site, view }: { r: DeliveryRequest; site: Site; view: ProjectView }) {
  const w = passWindow({ date: r.date, slot: r.slot }, view.project.settings);
  return (
    <div className="ticket">
      <div className="ticket-top">
        <div><div className="t1">{r.material}</div><div className="t2">{fmtDate(r.date)} · {fmtTime(r.slot)} · {site.gate(r.gateId).name}</div></div>
        <span className="pill" style={{ background: 'rgba(255,255,255,.16)', color: '#fff' }}>Gate pass</span>
      </div>
      <div className="ticket-body">
        <QrSvg code={r.passCode as string} />
        <div className="pcode">{r.passCode}</div>
        <p className="small muted">Show this to Access Control at the gate. Arrive between <b>{fmtClock(w.open)}</b> and <b>{fmtClock(w.close)}</b>.</p>
        <dl className="kv" style={{ textAlign: 'left', width: '100%' }}>
          <dt>Staging</dt><dd>{site.zone(r.zoneId).name}</dd>
          <dt>Load</dt><dd>{r.quantity} {r.unit} · {plural(r.pallets, 'pallet')}</dd>
          <dt>Contact</dt><dd>{r.pocName}, {r.pocPhone}</dd>
        </dl>
      </div>
    </div>
  );
}

/** Rules context for live checks: what this person may see plus everyone else's anonymous capacity. */
export function rulesCtx(view: ProjectView, site: Site): RequestContext {
  const p = view.project;
  return {
    now: site.wall, settings: p.settings, gates: p.gates, zones: p.zones, activities: p.activities,
    subs: view.subs.some((s) => s.id === view.mySub.id) ? view.subs : view.subs.concat(view.mySub),
    requests: (view.requests as BookedRequest[]).concat(view.occupancy as BookedRequest[]),
  };
}

// ---------------------------------------------------------------- Confirm Delivery

export function ConfirmPanel() {
  const { view, site } = useApp();
  const home = useHome();
  const [pick, setPick] = useState<string | null>(null);
  if (!view || !site) return null;
  const list = view.requests.filter((r) => r.subId === view.mySub.id && r.status === 'approved' && r.date >= site.today && site.passOf(r)?.status === 'active').sort(byWhen);
  if (!list.length) {
    const rev = view.requests.filter((r) => r.subId === view.mySub.id && r.status === 'review').length;
    return <Empty><b>No gate passes yet.</b><span>{rev ? plural(rev, 'request') + ' waiting for review. ' : ''}Approved deliveries show their QR pass here.</span><button className="btn primary" onClick={() => home.openTab('schedule')}>Schedule a delivery</button></Empty>;
  }
  const r = list.find((x) => x.id === pick) || list[0];
  return (
    <>
      {list.length > 1 ? (
        <div className="chips" role="group" aria-label="Choose a delivery">
          {list.map((x) => <button key={x.id} className="chip" aria-pressed={x.id === r.id} onClick={() => setPick(x.id)}>{fmtDate(x.date)} {fmtTime(x.slot)}</button>)}
        </div>
      ) : null}
      <Ticket r={r} site={site} view={view} />
    </>
  );
}

// ---------------------------------------------------------------- Schedule Delivery

interface Form {
  id: string | null; activityId: string; gateId: string; date: string; slot: string; zoneId: string; material: string; quantity: string; unit: string;
  pallets: string; weightLbs: string; carrier: string; truck: string; pocName: string; pocPhone: string; justification: string;
}

function blankForm(view: ProjectView, site: Site, me: { first: string; last: string; phone: string }): Form {
  const g = view.project.gates[0];
  const n = g ? nextOpenSlot(rulesCtx(view, site), g.id) : null;
  return { id: null, activityId: '', gateId: g ? g.id : '', date: n ? n.date : addDays(site.today, 2), slot: '', zoneId: '', material: '', quantity: '', unit: 'pcs', pallets: '', weightLbs: '', carrier: '', truck: '', pocName: (me.first + ' ' + me.last).trim(), pocPhone: me.phone, justification: '' };
}
function formFromRequest(r: DeliveryRequest): Form {
  return { id: r.id, activityId: r.activityId, gateId: r.gateId, date: r.date, slot: r.slot, zoneId: r.zoneId, material: r.material, quantity: String(r.quantity), unit: r.unit, pallets: String(r.pallets), weightLbs: r.weightLbs === null ? '' : String(r.weightLbs), carrier: r.carrier || '', truck: r.truck || '', pocName: r.pocName, pocPhone: r.pocPhone, justification: r.justification || '' };
}

function CheckSummary({ ev }: { ev: Evaluation }) {
  const filled = ev.checks.every((k) => k.status !== 'skip') && ev.checks[0].status === 'pass';
  const fails = ev.checks.filter((k) => k.status === 'fail'); const flags = ev.checks.filter((k) => k.status === 'flag');
  const cls = !filled ? 'none' : fails.length ? 'bad' : flags.length ? 'rev' : 'ok';
  const msg = !filled ? 'Fill in the request to run the checks.' : fails.length ? `${plural(fails.length, 'problem')} to fix before this can be approved.` : flags.length ? 'Passes the rules. A project admin will review it.' : `All ${ev.checks.length} checks pass. It will be approved automatically.`;
  const icon = { pass: '✓', fail: '✕', flag: '!', skip: '–' };
  return (
    <div aria-live="polite">
      <div className={'checksum ' + cls}>{msg}</div>
      {filled && (fails.length || flags.length) ? <ul className="reasons" style={{ marginTop: 8 }}>{fails.concat(flags).map((k) => <li key={k.id} className={k.status === 'flag' ? 'flag' : ''}><b>{k.title}</b>{k.remedy}</li>)}</ul> : null}
      <details className="more" style={{ marginTop: 8 }}><summary>See all {ev.checks.length} checks</summary>
        <ul className="checks">{ev.checks.map((k) => <li key={k.id}><span className={'ic ' + k.status} aria-hidden="true">{icon[k.status]}</span><span>{k.label}<span className="sr-only"> {k.status}</span></span></li>)}</ul>
      </details>
    </div>
  );
}

export function SchedulePanel() {
  const app = useApp();
  const home = useHome();
  const { view, site } = app;
  const [form, setForm] = useState<Form | null>(null);
  const [result, setResult] = useState<{ request: DeliveryRequest; nextOpen: { date: string; slot: string; label: string } | null } | null>(null);
  const [busy, setBusy] = useState(false);
  const [editingSeen, setEditingSeen] = useState<string | null>(null);
  if (!view || !site || !app.home) return null;

  // "Reschedule or edit" from My Deliveries
  if (home.editing && home.editing !== editingSeen) {
    const r = view.requests.find((x) => x.id === home.editing);
    setEditingSeen(home.editing);
    if (r) { setForm(formFromRequest(r)); setResult(null); }
  }
  const f = form || blankForm(view, site, app.home.me);
  const set = (k: keyof Form, v: string) => {
    const next = Object.assign({}, f, { [k]: v });
    if (k === 'gateId' || k === 'date') { const b = slotBoard(rulesCtx(view, site), next.gateId, next.date, next.id || undefined); const cur = b.find((s) => s.slot === next.slot); if (!cur || !cur.open) next.slot = ''; }
    setForm(next);
  };
  const p = view.project; const s = p.settings; const sub = view.mySub;
  const acts = p.activities.filter((a) => !sub.trade || a.trade === sub.trade || a.trade === 'General');
  const ctx = rulesCtx(view, site);
  const board = slotBoard(ctx, f.gateId, f.date, f.id || undefined);
  const act = p.activities.find((a) => a.id === f.activityId);
  const days = f.date ? stagingDays(f.date, act).days : [];
  const req = Object.assign({}, f, { id: f.id || 'draft', subId: sub.id, quantity: f.quantity === '' ? '' : Number(f.quantity), pallets: f.pallets === '' ? '' : Number(f.pallets) });
  const ev = evaluateRequest(req, ctx);
  const needJust = !!(act && f.date && daysBetween(f.date, act.start) > s.maxDaysBeforeInstall);

  async function submit(e: FormEvent) {
    e.preventDefault();
    const missing = ev.checks.find((k) => k.reason === 'R01');
    if (missing) { app.toast(missing.title + '. ' + missing.remedy); return; }
    setBusy(true);
    const r = await app.run(() => app.api.submitRequest(view!.project.id, {
      id: f.id, activityId: f.activityId, gateId: f.gateId, date: f.date, slot: f.slot, zoneId: f.zoneId, material: f.material, quantity: f.quantity, unit: f.unit,
      pallets: f.pallets, weightLbs: f.weightLbs === '' ? null : f.weightLbs, carrier: f.carrier, truck: f.truck, pocName: f.pocName, pocPhone: f.pocPhone, justification: needJust ? f.justification : '',
    }));
    setBusy(false);
    if (r) { setResult(r); setForm(null); home.setEditing(null); setEditingSeen(null); await app.refresh(); document.getElementById('tab-schedule')?.scrollIntoView({ behavior: 'smooth', block: 'start' }); }
  }

  if (result) {
    const r = view.requests.find((x) => x.id === result.request.id) || result.request;
    const st = r.status === 'approved' ? site.statusOf(r) : r.status;
    const head: Record<string, [string, string]> = {
      approved: ['Approved', 'Your gate pass is ready. It’s in Confirm Delivery and your email.'],
      review: ['Sent for review', 'It passed the rules. A project admin will approve or reject it. You’ll get an email.'],
      rejected: ['Not approved', 'Fix the items below and submit again.'],
    };
    const [h, sub2] = head[st] || [LABEL[st] || st, ''];
    return (
      <div className="card stack">
        <div className="between"><span className="h3">{h}</span><Pill st={st} /></div>
        <p className="small">{sub2}</p>
        {st === 'approved' && r.passCode ? <Ticket r={r} site={site} view={view} /> : <Reasons r={r} />}
        {result.nextOpen && st === 'rejected' ? (
          <button className="btn primary" onClick={() => { setForm(Object.assign(formFromRequest(r), { date: result.nextOpen!.date, slot: result.nextOpen!.slot })); setResult(null); }}>Use next open slot: {result.nextOpen.label}</button>
        ) : null}
        <div className="row">
          {st === 'rejected' ? <button className="btn" onClick={() => { setForm(formFromRequest(r)); setResult(null); }}>Fix and resubmit</button> : null}
          <button className={'btn ' + (st === 'rejected' ? '' : 'primary')} style={{ flex: 1 }} onClick={() => { setResult(null); setForm(null); }}>Book another delivery</button>
        </div>
      </div>
    );
  }

  return (
    <>
      {sub.suspended ? <div className="note warn">Your company’s booking rights are suspended on this project. Contact the project admin.</div> : null}
      {f.id ? <div className="note">Editing a booked delivery. Saving runs every check again and replaces the gate pass.</div> : null}
      {view.maintenance ? <div className="note">Maintenance mode: this booking is labelled as maintenance.</div> : null}
      <form className="stack" onSubmit={submit} noValidate>
        <span className="section-t">What and why</span>
        <Field id="f_activityId" label="Look-ahead activity" hint={act ? `${fmtDate(act.start)} to ${fmtDate(act.finish)}. Deliver no earlier than ${fmtDate(addDays(act.start, -s.maxDaysBeforeInstall))}.` : 'Only activities from the current 3-week look-ahead are listed.'}>
          <select id="f_activityId" value={f.activityId} onChange={(e) => set('activityId', e.target.value)}>
            <option value="">Choose the activity this supports</option>
            {acts.map((a) => <option key={a.id} value={a.id}>{a.id} · {a.name} · starts {fmtDate(a.start)}</option>)}
          </select>
        </Field>
        <Field id="f_material" label="Material"><input id="f_material" value={f.material} placeholder="e.g. Busway sections, 4000A" autoComplete="off" maxLength={120} onChange={(e) => set('material', e.target.value)} /></Field>
        <div className="grid2">
          <Field id="f_quantity" label="Quantity"><input id="f_quantity" inputMode="decimal" value={f.quantity} onChange={(e) => set('quantity', e.target.value)} /></Field>
          <Field id="f_unit" label="Unit"><select id="f_unit" value={f.unit} onChange={(e) => set('unit', e.target.value)}>{UNITS.map((u) => <option key={u} value={u}>{u}</option>)}</select></Field>
          <Field id="f_pallets" label="Pallets or skids"><input id="f_pallets" inputMode="numeric" value={f.pallets} onChange={(e) => set('pallets', e.target.value)} /></Field>
          <Field id="f_weightLbs" label="Weight, lb (optional)"><input id="f_weightLbs" inputMode="numeric" value={f.weightLbs} onChange={(e) => set('weightLbs', e.target.value)} /></Field>
        </div>
        <span className="section-t">When and where</span>
        <div className="grid2">
          <Field id="f_gateId" label="Gate"><select id="f_gateId" value={f.gateId} onChange={(e) => set('gateId', e.target.value)}>{p.gates.map((g) => <option key={g.id} value={g.id}>{g.name}</option>)}</select></Field>
          <Field id="f_date" label="Date"><input type="date" id="f_date" value={f.date} min={site.today} onChange={(e) => set('date', e.target.value)} /></Field>
        </div>
        <div className="field"><span className="label" id="slotLbl">Time slot</span>
          <div className="slots" role="group" aria-labelledby="slotLbl">
            {board.map((b) => {
              const note = b.closedDay ? 'Gate closed' : b.tooSoon ? 'Under ' + s.minNoticeHours + ' h' : b.left === 0 ? 'Full' : b.left + ' open';
              return <button key={b.slot} type="button" className={'slot ' + (b.open ? '' : 'off')} aria-pressed={f.slot === b.slot} onClick={() => set('slot', b.slot)}><b>{b.label}</b><small>{note}</small></button>;
            })}
          </div>
        </div>
        <Field id="f_zoneId" label="Staging zone">
          <select id="f_zoneId" value={f.zoneId} onChange={(e) => set('zoneId', e.target.value)}>
            <option value="">Choose a zone</option>
            {p.zones.map((z) => { const left = Math.max(0, z.capacityPallets - zonePeak(ctx.requests, z.id, days, f.id || undefined)); return <option key={z.id} value={z.id}>{z.name} · {left} of {z.capacityPallets} pallets free</option>; })}
          </select>
        </Field>
        {needJust ? (
          <Field id="f_justification" label="Why does it need to come early?" hint="Early deliveries go to a project admin for review.">
            <textarea id="f_justification" placeholder="e.g. Factory ships once; crane booked" maxLength={500} value={f.justification} onChange={(e) => set('justification', e.target.value)} />
          </Field>
        ) : null}
        <span className="section-t">Truck and contact</span>
        <div className="grid2">
          <Field id="f_carrier" label="Carrier"><input id="f_carrier" value={f.carrier} autoComplete="off" maxLength={80} onChange={(e) => set('carrier', e.target.value)} /></Field>
          <Field id="f_truck" label="Truck no. (optional)"><input id="f_truck" value={f.truck} autoComplete="off" maxLength={40} onChange={(e) => set('truck', e.target.value)} /></Field>
          <Field id="f_pocName" label="Onsite contact"><input id="f_pocName" value={f.pocName} autoComplete="off" maxLength={80} onChange={(e) => set('pocName', e.target.value)} /></Field>
          <Field id="f_pocPhone" label="Contact phone"><input id="f_pocPhone" inputMode="tel" value={f.pocPhone} autoComplete="off" onChange={(e) => set('pocPhone', e.target.value)} /></Field>
        </div>
        <CheckSummary ev={ev} />
        <div className="row">
          {f.id ? <button type="button" className="btn" onClick={() => { setForm(null); home.setEditing(null); setEditingSeen(null); }}>Discard changes</button> : null}
          <button className="btn primary" style={{ flex: 1 }} type="submit" disabled={busy}>{busy ? 'Checking…' : f.id ? 'Save and re-check' : 'Submit request'}</button>
        </div>
      </form>
    </>
  );
}

