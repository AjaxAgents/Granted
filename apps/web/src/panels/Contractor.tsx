export function DeliveryRow({ r, site, open, onClick }: { r: DeliveryRequest; site: Site; open: boolean; onClick: () => void }) {
  const st = site.statusOf(r);
  return (
    <button className="item" onClick={onClick} aria-expanded={open}>
      <span className="when">{fmtDate(r.date)}<span>{fmtTime(r.slot)}</span></span>
      <span><span className="ititle">{r.material}</span>
        <span className="isub" style={{ display: 'block' }}>{r.maintenance ? <><b>Maintenance</b> · </> : null}{site.gate(r.gateId).name} · {site.zone(r.zoneId).name}{r.passCode ? <> · <span className="mono">{r.passCode}</span></> : null}</span>
      </span>
      <Pill st={st} />
    </button>
  );
}

function Detail({ r }: { r: DeliveryRequest }) {
  const app = useApp(); const home = useHome();
  const { view, site } = app;
  if (!view || !site) return null;
  const st = site.statusOf(r);
  const act = view.project.activities.find((a) => a.id === r.activityId);
  const canChange = (st === 'approved' || st === 'review') && r.date >= site.today;
  return (
    <div className="card stack-s" style={{ marginTop: -4 }}>
      <Reasons r={r} />
      <dl className="kv">
        <dt>Load</dt><dd>{r.quantity} {r.unit} · {plural(r.pallets, 'pallet')}</dd>
        <dt>Activity</dt><dd>{act ? act.id + ' ' + act.name : r.activityId || '—'}</dd>
        <dt>Truck</dt><dd>{[r.carrier, r.truck].filter(Boolean).join(', ') || '—'}</dd>
        <dt>Contact</dt><dd>{r.pocName}{r.pocPhone ? ', ' + r.pocPhone : ''}</dd>
        <dt>Booked by</dt><dd>{r.submittedBy}</dd>
        <dt>Decided</dt><dd>{r.decidedBy || ''}{r.decidedAt ? ', ' + site.label(r.decidedAt) : ''}</dd>
      </dl>
      {canChange ? (
        <div className="row">
          <button className="btn sm" onClick={() => { home.setEditing(r.id); home.openTab('schedule'); }}>Reschedule or edit</button>
          <ConfirmButton label="Cancel delivery" confirm="Yes, cancel it" onConfirm={async () => { if (await app.run(() => app.api.cancelRequest(r.id), 'Cancelled. Access Control was told.') !== undefined) await app.refresh(); }} />
        </div>
      ) : null}
    </div>
  );
}

export function MinePanel() {
  const app = useApp(); const home = useHome();
  const { view, site } = app;
  const [open, setOpen] = useState<string | null>(null);
  if (!view || !site) return null;
  const mine = view.requests.filter((r) => r.subId === view.mySub.id);
  if (!mine.length) return <Empty><b>No deliveries yet.</b><button className="btn primary" onClick={() => home.openTab('schedule')}>Schedule a delivery</button></Empty>;
  const up = mine.filter((r) => r.date >= site.today && (r.status === 'approved' || r.status === 'review')).sort(byWhen);
  const past = mine.filter((r) => !up.includes(r)).sort((a, b) => byWhen(b, a));
  const block = (r: DeliveryRequest) => <div key={r.id} className="stack-s"><DeliveryRow r={r} site={site} open={open === r.id} onClick={() => setOpen(open === r.id ? null : r.id)} />{open === r.id ? <Detail r={r} /> : null}</div>;
  return (
    <>
      {up.length ? <div className="list">{up.map(block)}</div> : <p className="empty">No upcoming deliveries.</p>}
      {past.length ? <details className="more"><summary>Past, cancelled and rejected ({past.length})</summary><div className="list" style={{ marginTop: 8 }}>{past.map(block)}</div></details> : null}
    </>
  );
}

